// =============================================================================
// TextRenderer_PlatformBase Implementation
// =============================================================================
TextRenderer_PlatformBase::TextRenderer_PlatformBase(Animator *animator, uint16 defaultX, uint16 defaultY, uint16 defaultColor)
	: TextRenderer(), _animator(animator), _textPtr(nullptr), _needDraw(false),
	  _printDelay(0), _printDelayCounter(0), _color(defaultColor),
	  _startX(defaultX), _startY(defaultY), _curX(defaultX), _curY(defaultY),
	  _font(nullptr), _fontSize(0), _charWidthTable(nullptr), _charWidthTableSize(0) {
}

TextRenderer_PlatformBase::~TextRenderer_PlatformBase() {
}

void TextRenderer_PlatformBase::setFont(const uint8 *font, uint32 fontSize) {
	_font = font;
	_fontSize = fontSize;
}

void TextRenderer_PlatformBase::setCharWidthTable(const uint8 *table, uint32 tableSize) {
	_charWidthTable = table;
	_charWidthTableSize = tableSize;
}

void TextRenderer_PlatformBase::enqueuePrintJob(const uint8 *text) {
	_textPtr = text;
	_needDraw = true;
	_printDelayCounter = _printDelay = 0;
	_curX = _startX;
	_curY = _startY;
}

void TextRenderer_PlatformBase::setPrintDelay(int delay) {
	_printDelay = delay;
}

void TextRenderer_PlatformBase::reset() {
	_textPtr = nullptr;
	_needDraw = false;
	_curX = _startX;
	_curY = _startY;
	if (_animator)
		_animator->resetTextFields();
}

void TextRenderer_PlatformBase::draw() {
	if (!_needDraw || !_textPtr || !_animator)
		return;

	if (_printDelay > 0 && ++_printDelayCounter < _printDelay)
		return;
	_printDelayCounter = 0;

	uint16 firstRow = _curY;
	const uint8 *s = _textPtr;

	while (*s != 0) {
		uint8 in = *s++;
		if (in == 0x0A) {
			// Newline
			_curY += 12;
			_curX = _startX;
		} else if (in == 0xFD) {
			// Color select
			_color = *s++;
		} else if (in == 0xFC) {
			// Pause / delay
			_textPtr = s;
			return;
		} else {
			drawGlyph(in);
		}
	}

	_textPtr = s;
	_needDraw = false;
	_animator->renderTextBuffer(firstRow, 32);
}

void TextRenderer_PlatformBase::drawGlyph(uint8 glyphCode) {
	uint8 *tb = _animator->getTextRenderBuffer();
	if (!tb)
		return;

	int w = _animator->realScreenWidth();
	int h = _animator->realScreenHeight();

	if (glyphCode < 32 || glyphCode > 127)
		glyphCode = '?';

	const uint8 *glyphData = kPlatformFont8x8[glyphCode - 32];
	for (int y = 0; y < 8; ++y) {
		int py = _curY + y;
		if (py < 0 || py >= h)
			continue;
		uint8 row = glyphData[y];
		for (int x = 0; x < 8; ++x) {
			int px = _curX + x;
			if (px < 0 || px >= w)
				continue;
			if (row & (1 << (7 - x))) {
				tb[py * w + px] = (uint8)_color;
			}
		}
	}
	_curX += 8;
}

// =============================================================================
// TextRenderer_PSX (PlayStation: 320x240, shadow/border outline)
// =============================================================================
TextRenderer_PSX::TextRenderer_PSX(Animator *animator)
	: TextRenderer_PlatformBase(animator, 16, 172, 15) {
}

TextRenderer_PSX::~TextRenderer_PSX() {
}

void TextRenderer_PSX::drawGlyph(uint8 glyphCode) {
	uint8 *tb = _animator->getTextRenderBuffer();
	if (!tb)
		return;

	int w = _animator->realScreenWidth();
	int h = _animator->realScreenHeight();

	if (glyphCode < 32 || glyphCode > 127)
		glyphCode = '?';

	const uint8 *glyphData = kPlatformFont8x8[glyphCode - 32];

	// Draw 1-pixel drop shadow and text body
	for (int y = 0; y < 8; ++y) {
		int py = _curY + y;
		if (py < 0 || py >= h)
			continue;
		uint8 row = glyphData[y];
		for (int x = 0; x < 8; ++x) {
			int px = _curX + x;
			if (px < 0 || px >= w)
				continue;
			if (row & (1 << (7 - x))) {
				if (py + 1 < h && px + 1 < w)
					tb[(py + 1) * w + (px + 1)] = 0; // Shadow
				tb[py * w + px] = (uint8)_color;      // Foreground
			}
		}
	}
	_curX += 7; // Proportional kerning
}

