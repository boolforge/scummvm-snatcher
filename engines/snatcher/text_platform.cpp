// =============================================================================
// TextRenderer Factory Dispatcher
// =============================================================================
TextRenderer *TextRenderer::create(Common::Platform platform, Animator *animator) {
	switch (platform) {
	case Common::kPlatformSegaCD:
		return createSegaTextRenderer(animator);
	case Common::kPlatformPSX:
		return new TextRenderer_PSX(animator);
	case Common::kPlatformSaturn:
		return new TextRenderer_Saturn(animator);
	case Common::kPlatformPCEngine:
		return new TextRenderer_PCE(animator);
	case Common::kPlatformPC98:
		return new TextRenderer_PC88(animator);
	default:
		return new TextRenderer_MSX2(animator);
	}
}

